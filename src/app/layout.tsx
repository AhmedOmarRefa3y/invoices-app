import type { Metadata } from "next";
import { Vazirmatn } from "next/font/google";

import "./globals.css";

import Image from "next/image";
import bgIamge from "../../public/bg2.svg";
import prismaDb from "./lib/prisma";
import { Providers } from "./providers/Providers";

const inter = Vazirmatn({ subsets: ["arabic"], weight: "400" });

export const metadata: Metadata = {
    title: "Invoice Management System",
    description: "Generated by create next app",
};

export default async function RootLayout({
    children,
}: {
    children: React.ReactNode;
}) {
    const products = await prismaDb.product.findMany({
        include: {
            Part: true,
        },
    });
    const categories = await prismaDb.catgories.findMany();
    const customers = await prismaDb.customer.findMany();
    const units = await prismaDb.units.findMany();
    return (
        <html lang="ar" dir="rtl" className="light">
            <body
                className={`${inter.className} relative w-full mx-auto bg-white`}
            >
                <Providers
                    categories={categories}
                    products={products}
                    customers={customers}
                    units={units}
                >
                    {/* <div className="absolute inset-0 max-h-screen overflow-hidden">
                        <Image
                            src={bgIamge}
                            alt={"bg"}
                            className="object-none"
                        />
                    </div> */}
                    {children}
                </Providers>
            </body>
        </html>
    );
}
